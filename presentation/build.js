/** Пузырёк прибора с мнемосхемы — сквозной мотив презентации. */
function bubble(s, code, x, y, d, fill, stroke) {
  s.addShape(p.ShapeType.ellipse, {
    x, y, w: d, h: d, fill: { color: fill || BG },
    line: { color: stroke || BLUE, width: 1.75 },
  });
  s.addText(code, {
    x, y, w: d, h: d, align: 'center', valign: 'middle',
    fontFace: BODY, fontSize: d > 0.6 ? 13 : 10, bold: true, color: stroke || BLUE,
  });
}

function card(s, x, y, w, h) {
  s.addShape(p.ShapeType.roundRect, {
    x, y, w, h, rectRadius: 0.06,
    fill: { color: PANEL }, line: { color: LINE, width: 1 },
  });
}

/**
 * Заголовок внутри карточки. Возвращает y, с которого начинать тело, —
 * чтобы отступ был одинаковым везде и текст не наезжал на заголовок.
 */
function head(s, x, y, w, text, color, size) {
  s.addText(text, { x, y, w, h: 0.3, margin: 0,
    fontFace: BODY, fontSize: size || 15, bold: true, color });
  return y + 0.46;
}

/** Обычный содержательный слайд: фон, пузырёк-мотив, заголовок. */
function slide(code, title, sub) {
  const s = p.addSlide();
  s.background = { color: BG };
  bubble(s, code, M, 0.42, 0.66);
  s.addText(title, {
    x: 1.38, y: 0.36, w: W - 1.38 - M, h: 0.5, margin: 0,
    fontFace: H1, fontSize: 30, bold: true, color: TXT, valign: 'middle',
  });
  if (sub) s.addText(sub, {
    x: 1.38, y: 0.86, w: W - 1.38 - M, h: 0.3, margin: 0,
    fontFace: BODY, fontSize: 13, color: MUT, valign: 'top',
  });
  return s;
}

/** Крупная цифра с подписью. */
function stat(s, x, y, w, value, label, color) {
  s.addText(value, {
    x, y, w, h: 0.62, margin: 0,
    fontFace: H1, fontSize: 32, bold: true, color: color || FIRE,
  });
  s.addText(label, {
    x, y: y + 0.6, w, h: 0.5, margin: 0,
    fontFace: BODY, fontSize: 11.5, color: MUT, lineSpacing: 15,
  });
}

function bullets(s, items, x, y, w, h, size) {
  const fs = size || 14;
  s.addText(items.map((t, i) => ({
    text: t, options: { bullet: true, breakLine: i !== items.length - 1 },
  })), {
    x, y, w, h, margin: 0, fontFace: BODY, fontSize: fs,
    color: TXT, paraSpaceAfter: 7, lineSpacing: Math.round(fs * 1.25),
  });
}

/** Пара «жирный заголовок + пояснение» — правая колонка у слайдов со скриншотом. */
function note(s, x, y, w, title, text, tw) {
  s.addText(title, { x, y, w, h: 0.28, margin: 0,
    fontFace: BODY, fontSize: 13, bold: true, color: BLUE });
  s.addText(text, { x, y: y + 0.3, w, h: tw || 0.75, margin: 0,
    fontFace: BODY, fontSize: 11.5, color: MUT, lineSpacing: 15 });
}

